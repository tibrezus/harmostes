#!/usr/bin/env bash
# Release gate (ADR-0020, Amendment 2026-10-26).
#
# The ONLY path from merged conventional commits to a shipped version runs
# through this gate. It enforces three rules:
#
#   1. PROVENANCE — the pending release PR must be release-please's own
#      (body marker "generated with Release Please"). A hand-rolled
#      "Manual release PR" is rejected and the run goes RED (#771/#782 are
#      the cautionary tales: feat shipped as patch, changelog entry lost).
#   2. PATCH-ONLY AUTOMERGE — if the bump is a patch (X.Y.Z → X.Y.Z+1),
#      the release PR arms auto-merge exactly as the pre-gate flow did.
#   3. OWNER-GATED MINORS/MAJORS — any larger bump is HELD until the
#      `minor-approved` label is set by the owner. A held release PR keeps
#      absorbing later releasable merges (release-please updates it in
#      place), so a milestone's ten feats batch into ONE minor when the
#      owner labels it once.
#
# Idempotent: run on every push to main and on the `minor-approved` label
# event; holds post at most one comment (marker-deduped).
set -euo pipefail

LABEL="${GATE_LABEL:-minor-approved}"
BOT_MARKER="generated with Release Please"
HOLD_MARKER="release-gate: minor hold"
REJECT_MARKER="release-gate: provenance reject"

die() { echo "::error::$*" >&2; exit 1; }

command -v gh >/dev/null || die "gh is required"

PR="$(gh pr list -R "$GITHUB_REPOSITORY" --label "autorelease: pending" --state open --json number --jq '.[0].number')"
if [ -z "$PR" ]; then
  echo "no pending release PR — nothing to gate"
  exit 0
fi
echo "gating release PR #$PR"

meta="$(gh pr view "$PR" -R "$GITHUB_REPOSITORY" --json title,body,labels --jq '{t: .title, b: .body, l: [.labels[].name]}')"
title="$(jq -r .t <<<"$meta")"
body="$(jq -r .b <<<"$meta")"
labels="$(jq -r '.l | join(",")' <<<"$meta")"

has_label() { [[ ",$labels," == *",$1,"* ]]; }
comment_once() { # $1 = dedup marker, $2 = body
  local existing
  existing="$(gh pr view "$PR" -R "$GITHUB_REPOSITORY" --json comments --jq '[.comments[].body] | join("\n---\n")' || true)"
  if ! grep -qF "$1" <<<"$existing"; then
    gh pr comment "$PR" -R "$GITHUB_REPOSITORY" --body "$2" >/dev/null
  fi
}

# --- Rule 1: provenance ------------------------------------------------------
if ! grep -qF "$BOT_MARKER" <<<"$body"; then
  comment_once "$REJECT_MARKER" "$(cat <<EOF
$REJECT_MARKER

This release PR was **not generated by release-please** (missing the bot
body marker), so the release gate refuses to merge it. Hand-rolled release
PRs bypass the changelog and version bookkeeping — #782 shipped a \`feat:\`
as a patch and #781 lost its changelog entry that way (ADR-0020, Amendment
2026-10-26).

If the bot is genuinely stuck, fix the cause (usually an unconsumable
commit title) and re-run the *Release Please* workflow — never substitute
a manual PR for it.
EOF
)"
  die "release PR #$PR is not release-please's own — refusing to merge (see PR comment)"
fi

# --- Classify the bump -------------------------------------------------------
title_re='^chore\(main\): release ([0-9]+)\.([0-9]+)\.([0-9]+)$'
if ! [[ "$title" =~ $title_re ]]; then
  die "release PR #$PR title is not 'chore(main): release X.Y.Z' — cannot classify: '$title'"
fi
next_major="${BASH_REMATCH[1]}" next_minor="${BASH_REMATCH[2]}"

prev_tag="$(gh release list -R "$GITHUB_REPOSITORY" --limit 1 --json tagName --jq '.[0].tagName' || true)"
prev_major="" prev_minor=""
if [ -n "$prev_tag" ]; then
  prev_re='^v([0-9]+)\.([0-9]+)\.[0-9]+$'
  [[ "$prev_tag" =~ $prev_re ]] && { prev_major="${BASH_REMATCH[1]}"; prev_minor="${BASH_REMATCH[2]}"; }
fi

is_patch=false
if [ -n "$prev_major" ] && [ "$prev_major" = "$next_major" ] && [ "$prev_minor" = "$next_minor" ]; then
  is_patch=true
fi

# --- Rule 3: minors/majors need the owner's label ----------------------------
if [ "$is_patch" = false ] && ! has_label "$LABEL"; then
  comment_once "$HOLD_MARKER" "$(cat <<EOF
$HOLD_MARKER

This release bumps the **minor/major** version (\`$title\`), and per
ADR-0020 (Amendment 2026-10-26) minors are **owner-gated**: the release
waits for the \`$LABEL\` label on this PR.

Nothing is lost while it waits — release-please keeps updating this PR as
more merges land, so a milestone's features batch into ONE version. Add
the label when the milestone (or a single feature) should ship.
EOF
)"
  echo "HELD: '$title' is a minor/major bump — waiting for the '$LABEL' label"
  exit 0
fi

# --- Rule 2: automerge (patch, or labeled minor/major) -----------------------
if [ "$is_patch" = true ]; then
  echo "patch bump ('$title') — arming auto-merge"
else
  echo "'$title' carries '$LABEL' — arming auto-merge"
fi
gh pr merge "$PR" -R "$GITHUB_REPOSITORY" --auto --squash
# Strict branch protection ("require branch up to date") stalls an armed
# automerge whenever ANY main merge lands between arming and completion —
# including non-releasable ci/chore merges, which release-please does not
# consider worth updating its PR for. Keep the release branch current so
# the armed merge can land; every push to main re-runs this gate, so the
# cycle converges.
if gh pr view "$PR" -R "$GITHUB_REPOSITORY" --json mergeStateStatus --jq -e '. == "BEHIND"'; then
  echo "release PR #$PR is BEHIND — updating branch"
  gh pr update-branch "$PR" -R "$GITHUB_REPOSITORY"
fi
